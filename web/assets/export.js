/* Taking an answer out of the product.

   Markdown downloads as a file, and PDF goes through the browser's own print dialog rather than
   a rendering library. That choice is deliberate: a server-side PDF renderer needs native
   libraries that are awkward on Windows, and a client-side one turns charts into images and the
   text into something nobody can search. Print keeps the text selectable and costs nothing. */

import { formatValue, prettyColumn } from "./format.js";
import { toast } from "./ui.js";

function slug(text) {
  return String(text)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 60) || "answer";
}

/* An answer as Markdown, including the evidence as tables so the file stands on its own. */
export function toMarkdown(answer) {
  const lines = [`# ${answer.title}`, ""];
  lines.push(`> ${answer.question}`, "");

  const verified = Math.round((answer.verification_score || 0) * 100);
  lines.push(`**${verified}% of the figures were checked against the source data.**`, "");
  lines.push(answer.body.trim(), "");

  if (answer.removed_claims?.length) {
    lines.push(
      `_${answer.removed_claims.length} sentence(s) were removed because the data did not support them._`,
      "",
    );
  }
  for (const limitation of answer.limitations || (answer.limitation ? [answer.limitation] : [])) {
    lines.push(`_Worth knowing: ${limitation}_`, "");
  }

  lines.push("## Where these numbers came from", "");
  for (const step of answer.steps || answer.observations || []) {
    const id = step.source_id;
    lines.push(`### ${id} — ${step.purpose}`, "");
    if (step.ok === false) {
      lines.push(`_Not used: ${step.reason}_`, "");
      continue;
    }
    if (!step.rows?.length) {
      lines.push("_This search returned no rows._", "");
    } else {
      lines.push(markdownTable(step.columns, step.rows));
      lines.push("");
    }
    lines.push("```sql", (step.executed_sql || step.sql || "").trim(), "```", "");
  }

  const usage = answer.usage || {};
  const cost = answer.cost_usd ?? usage.cost_usd;
  const model = answer.model ?? usage.model;
  lines.push("---", "");
  lines.push(
    `Generated by Meridian${model ? ` using ${model}` : ""}` +
      `${cost === undefined ? "" : ` · cost $${Number(cost).toFixed(4)}`}` +
      ` · ${new Date().toLocaleString()}`,
  );
  return lines.join("\n");
}

function markdownTable(columns, rows) {
  const header = `| ${columns.map(prettyColumn).join(" | ")} |`;
  const divider = `| ${columns.map(() => "---").join(" | ")} |`;
  const body = rows
    .slice(0, 50)
    .map((row) => `| ${columns.map((c) => formatValue(c, row[c])).join(" | ")} |`)
    .join("\n");
  return [header, divider, body].join("\n");
}

export function downloadMarkdown(answer) {
  const blob = new Blob([toMarkdown(answer)], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = `${slug(answer.title)}.md`;
  document.body.append(link);
  link.click();
  link.remove();
  // Revoking immediately can cancel the download in some browsers; a tick is enough.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
  toast("Downloaded as a Markdown file.", "success");
}

export async function copyMarkdown(answer) {
  try {
    await navigator.clipboard.writeText(toMarkdown(answer));
    toast("Copied. Paste it into an email or a document.", "success");
  } catch {
    toast("Your browser blocked copying. Use Download instead.", "error");
  }
}

/* PDF via the browser's print dialog. The print stylesheet hides the navigation and expands
   every collapsed source, so the printed page contains the evidence rather than a row of
   closed summaries. */
export function printAnswer() {
  document.body.classList.add("printing");
  for (const node of document.querySelectorAll("details")) {
    node.dataset.wasOpen = String(node.open);
    node.open = true;
  }

  const restore = () => {
    document.body.classList.remove("printing");
    for (const node of document.querySelectorAll("details")) {
      if (node.dataset.wasOpen !== undefined) {
        node.open = node.dataset.wasOpen === "true";
        delete node.dataset.wasOpen;
      }
    }
    window.removeEventListener("afterprint", restore);
  };
  window.addEventListener("afterprint", restore);

  window.print();
  // Safari does not always fire afterprint, so the state is restored on a timer as well.
  setTimeout(restore, 3000);
}

/* The buttons every answer view shows, so the live and saved views cannot drift apart. */
export function exportActions() {
  return `
    <button class="btn btn-ghost btn-sm" data-export="copy">Copy</button>
    <button class="btn btn-ghost btn-sm" data-export="download">Download</button>
    <button class="btn btn-ghost btn-sm" data-export="print">Save as PDF</button>`;
}

export function bindExportActions(root, answer) {
  root.addEventListener("click", (event) => {
    const button = event.target.closest("[data-export]");
    if (!button) return;
    const action = button.dataset.export;
    if (action === "copy") copyMarkdown(answer);
    else if (action === "download") downloadMarkdown(answer);
    else if (action === "print") printAnswer();
  });
}
